def compute_dedup_delta(jd_theme_sets, jd_list):
    """The corpus re-scrapes some postings across dates (same company+role,
    different jd_id). Collapsing to one record per distinct posting and
    recomputing theme % shows how much that duplication skews the headline
    numbers — returns the largest absolute percentage-point shift across
    all themes.
    """
    sig_to_ids = defaultdict(list)
    for j in jd_list:
        m = re.match(r"\d{4}-\d{2}-\d{2}_(.+)", j["jd_id"])
        sig = m.group(1) if m else j["jd_id"]
        sig_to_ids[sig].append(j["jd_id"])

    dedup_ids = set()
    for ids in sig_to_ids.values():
        ids_sorted = sorted(ids)
        with_bullets = [i for i in ids_sorted if jd_theme_sets.get(i)]
        dedup_ids.add(with_bullets[0] if with_bullets else ids_sorted[0])

    n_full = sum(1 for v in jd_theme_sets.values() if v)
    n_dedup = sum(1 for i in dedup_ids if jd_theme_sets.get(i))
    if n_full == 0 or n_dedup == 0:
        return 0.0

    full_counts = Counter(t for themes in jd_theme_sets.values() for t in themes)
    dedup_counts = Counter(t for i in dedup_ids for t in jd_theme_sets.get(i, []))

    max_delta = 0.0
    for t in full_counts:
        full_pct = 100 * full_counts[t] / n_full
        dedup_pct = 100 * dedup_counts[t] / n_dedup
        max_delta = max(max_delta, abs(dedup_pct - full_pct))
    return round(max_delta, 1)


