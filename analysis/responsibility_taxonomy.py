"""
Responsibility-theme extraction and classification across the JD corpus.

Parses the "responsibilities" section out of each data/<jd_id>/jd_archive.md
(handles clean markdown headings, unstructured plain-text scrapes, and
condensed single-paragraph summaries), then classifies each bullet against a
fixed 16-theme taxonomy via keyword matching (multi-label — a bullet can hit
more than one theme).

For JDs the regex extractor can't parse at all (prose-only descriptions,
non-English heading phrasing, thin scrapes), falls back to
responsibility_bullets_llm.json — a hand/agent-curated jd_id -> [bullets] map
built by reading those files directly and interpreting the responsibilities,
rather than pattern-matching. Each output record's "source" field marks which
path produced it ("regex" or "llm_interpreted"). That fallback file is not
regenerated by this script; rebuild it (e.g. via an agent) when new
unparseable JDs show up, using the same jd_id keys.

Inputs (read from analysis/):
  responsibility_bullets_llm.json    — optional LLM-interpreted fallback bullets

Also cross-tabs the 16 responsibility themes against the Layer B codebook dimensions
in data.json (seniority, autonomy_level, jd_authorship, data_team_maturity, etc.) to
surface which specific responsibilities go with which behavioural traits. Pairs where
a theme's regex keywords and a dimension's own coding rubric detect the same textual
signal (e.g. the "Data Quality & Testing" theme vs. `testing_framing`) are flagged as
construct-overlap and excluded from the reported findings — crossing them would mostly
measure whether two classification methods agree with each other, not a substantive
relationship. See OVERLAP_PAIRS below and "Responsibility themes vs. Layer B dimensions"
in the generated .md for the full reasoning, including two relationships that were
manually stratification-checked (confounder-controlled) before being reported, and one
that looked real unstratified and was kept specifically as a documented negative result.

Outputs (written to analysis/):
  responsibility_bullets.json        — raw extracted bullets per JD, tagged by source
  responsibility_classification.json — per-JD theme sets + corpus-wide stats + example quotes + dimension relationships
  responsibility_taxonomy.md         — human-readable taxonomy reference + examples + dimension relationships

Run:
  python3 analysis/responsibility_taxonomy.py
"""

