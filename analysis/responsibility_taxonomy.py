def fmt_p(p):
    if p < 0.0001:
        return "p<0.0001"
    if p < 0.001:
        return "p<0.001"
    return f"p={p:.3f}" if p < 0.01 else f"p={p:.2f}"


def fmt_crosstab(crosstab):
    """crosstab: {value: (pct_or_None, n)} -> one line per value."""
    parts = []
    for val, (pct, n) in crosstab.items():
        parts.append(f"{val}: {pct}% (n={n})" if pct is not None else f"{val}: n/a (n={n})")
    return "; ".join(parts)


