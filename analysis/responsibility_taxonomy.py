CONDENSED_RESP_RE = re.compile(
    r'\b(?:Key |Main |Core )?Responsibilit(?:y|ies):\s*(.+)'
)
CONDENSED_STOP_RE = re.compile(
    r'\b(Requirements?|Skills?|Tools?|Tech(?:nology)? [Ss]tack|Team|Role|Qualifications?|Experience)\s*:',
)


def extract_condensed_paragraph(text: str) -> list[str]:
    """Handles the single-paragraph scrape format used by some batches:
    'Role blurb. Responsibilities: item one; item two; item three. Requirements: ...'
    — everything is one paragraph, semicolon-delimited, no bullets/headings.
    """
    m = CONDENSED_RESP_RE.search(text)
    if not m:
        return []
    rest = m.group(1)
    stop = CONDENSED_STOP_RE.search(rest)
    if stop:
        rest = rest[: stop.start()]
    parts = [p.strip(" .") for p in rest.split(";")]
    return [p for p in parts if len(p) > 10]


def extract_responsibility_bullets(text: str) -> list[str]:
    """Best-effort extraction of responsibility bullets from one jd_archive.md body."""
    lines = text.split("\n")

    # Path 1: clean markdown headings (## or ###). A matched section's end
    # boundary is the next heading at the SAME OR SHALLOWER level — a nested
    # subheading (e.g. "### Data Culture" under "## Key Responsibilities")
    # must not truncate the section, or everything after the first
    # subsection silently disappears.
    headings = [
        (i, len(l) - len(l.lstrip("#")), l.lstrip("#").strip())
        for i, l in enumerate(lines)
        if l.startswith("## ") or l.startswith("### ")
    ]
    if headings:
        collected = []
        for idx, (i, level, h) in enumerate(headings):
            hh = h.strip().rstrip(":")
            if START_RE.match(hh):
                start = i + 1
                end = len(lines)
                for j in range(idx + 1, len(headings)):
                    if headings[j][1] <= level:
                        end = headings[j][0]
                        break
                for bl in lines[start:end]:
                    bl = bl.strip()
                    if bl.startswith("- "):
                        collected.append(bl[2:].strip())
                    elif bl and not bl.startswith("#") and len(bl) > 15:
                        collected.append(bl)
        if collected:
            return collected

    # Path 2: heading-less plain-text scrape — each non-empty line is a unit;
    # a short, unpunctuated line matching START_RE opens the section, a short
    # line matching STOP_RE (or looking like a new section header) closes it.
    flat = [l.strip() for l in text.split("\n") if l.strip()]
    collected = []
    in_section = False
    count = 0
    for p in flat:
        # rstrip(".:?") not just ":" - some JD authors close a heading with a
        # stylistic ellipsis ("In this role, You will.."), double period, or
        # question mark ("What will you do?"), which the old ":"-only strip
        # left trailing, tripping the `not pp.endswith(".")` guard below and
        # silently making a genuine short heading register as a prose
        # sentence instead. Confirmed via the L'Oréal ("In this role, You
        # will..") and Aubay Portugal ("What will you do?") JDs in the
        # 2026-08-01 audit.
        pp = p.rstrip(".:?")
        short = len(pp) < 70 and not pp.endswith(".")
        if short and START_RE.match(pp):
            in_section = True
            count = 0
            continue
        if in_section:
            if short and STOP_RE.match(pp):
                in_section = False
                continue
            if short and count > 0 and re.match(r"^[A-Z][a-zA-Z ,&/'\-]{2,60}$", pp) and not p.endswith("."):
                in_section = False
                continue
            if len(p) > 15:
                collected.append(p)
            count += 1
            if count > 25:
                in_section = False
    if collected:
        return collected

    # Path 3 (fallback): condensed single-paragraph scrapes —
    # "Role blurb. Responsibilities: item one; item two. Requirements: ..."
    # — used by some batches where the whole posting is one summarized
    # paragraph with no headings or line breaks to key off of.
    return extract_condensed_paragraph(text)


def clean_bullet(b: str) -> str:
    b = re.sub(r"^[\-\*••]+\s*", "", b)
    b = re.sub(r"\*\*", "", b)
    return b.strip()


